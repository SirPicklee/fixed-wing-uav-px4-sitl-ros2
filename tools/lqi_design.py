#!/usr/bin/env python3
"""
Step 2 of the LQI design: gains for the TB2 at the 45 m/s trim point.

Longitudinal LQI (ported from uav-6dof-autopilot examples/lqi_longitudinal.py):
    x = [u, w, q, theta, e_h, xi_v]       u = [elevator, throttle]
    e_h  = h_ref - h          (its derivative is -h_dot, linearized below)
    xi_v = integral of (V_ref - V)
Lateral LQI (roll-angle tracking for an outer L1 guidance loop):
    x = [v, p, r, phi - phi_ref, xi_phi]  u = [aileron, rudder]
    xi_phi = integral of (phi_ref - phi)

Writes the gains and trim to a YAML file read by the ROS 2 controller node.

Usage:
  python tools/lqi_design.py ~/uav-6dof-autopilot [output.yaml]
"""

import math
import sys
from pathlib import Path

import numpy as np

AIRSPEED = 45.0     # m/s, matches FW_AIRSPD_TRIM
ALTITUDE = 100.0    # m, typical mission altitude above the runway

# Longitudinal weights: same as the reference nonlinear comparison
Q_LON = np.diag([0.1, 1.0, 1.0, 10.0, 0.5, 0.5])
R_LON = np.diag([100.0, 1.0])
# Lateral weights (Bryson's rule, 1 / max_acceptable^2): v 5 m/s, p and r
# 1 rad/s, phi error 30 deg, xi_phi 1 rad s; aileron 20 deg, rudder 15 deg
Q_LAT = np.diag([1 / 5.0**2, 1.0, 1.0, 1 / math.radians(30.0)**2, 1.0])
R_LAT = np.diag([1 / math.radians(20.0)**2, 1 / math.radians(15.0)**2])


def augment_lon(A, B, v0):
    """Append e_h (e_h' = w - v0*theta) and xi_v (xi_v' = -u)."""
    n = A.shape[0]
    C = np.zeros((2, n))
    C[0, 1], C[0, 3] = 1.0, -v0
    C[1, 0] = -1.0
    A_aug = np.block([[A, np.zeros((n, 2))], [C, np.zeros((2, 2))]])
    B_aug = np.vstack([B, np.zeros((2, B.shape[1]))])
    return A_aug, B_aug


def augment_lat(A, B):
    """Append xi_phi (xi_phi' = -phi deviation)."""
    n = A.shape[0]
    C = np.zeros((1, n))
    C[0, 3] = -1.0
    A_aug = np.block([[A, np.zeros((n, 1))], [C, np.zeros((1, 1))]])
    B_aug = np.vstack([B, np.zeros((1, B.shape[1]))])
    return A_aug, B_aug


def report(name, A_cl, describe):
    print(f"Closed-loop {name} modes:")
    for m in describe(A_cl):
        if m["type"] == "oscillatory":
            print(f"  oscillatory: wn={m['wn']:.3f} rad/s, zeta={m['zeta']:.3f}, period={m['period']:.2f} s")
        else:
            print(f"  real:        lambda={m['lambda'].real:+.4f} 1/s, tau={m['tau']:.2f} s")


def main():
    ref = Path(sys.argv[1]).expanduser()
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else None
    sys.path.insert(0, str(ref / "src"))
    from uavsim.dynamics import trim_level_flight
    from uavsim.linearize import describe_eigenvalues, lateral, linearize, longitudinal
    from uavsim.lqr import controllability_rank, lqr

    trim = trim_level_flight(AIRSPEED, ALTITUDE)
    A, B, _, _ = linearize(trim)
    A_lon, B_lon = augment_lon(*longitudinal(A, B), AIRSPEED)
    A_lat, B_lat = augment_lat(*lateral(A, B))

    np.set_printoptions(precision=4, suppress=True, linewidth=110)
    for name, Am, Bm, Q, R in (("longitudinal", A_lon, B_lon, Q_LON, R_LON),
                               ("lateral", A_lat, B_lat, Q_LAT, R_LAT)):
        rank = controllability_rank(Am, Bm)
        K, P, _ = lqr(Am, Bm, Q, R)
        # Independent check: P must satisfy the algebraic Riccati equation
        are = Am.T @ P + P @ Am - P @ Bm @ np.linalg.solve(R, Bm.T @ P) + Q
        print(f"\n{name}: controllability rank {rank} of {Am.shape[0]}, "
              f"Riccati residual {np.abs(are).max():.1e}")
        print("K =\n", K)
        report(name, Am - Bm @ K, describe_eigenvalues)
        if name == "longitudinal":
            K_lon = K
        else:
            K_lat = K

    # Rough authority check: control demanded by typical errors
    du = -K_lon @ np.array([0, 0, 0, 0, 10.0, 0])
    print(f"\n10 m altitude error  -> elevator {math.degrees(du[0]):+.2f} deg, throttle {du[1]:+.3f}")
    du = -K_lat @ np.array([0, 0, 0, math.radians(-30.0), 0])
    print(f"30 deg bank command  -> aileron {math.degrees(du[0]):+.2f} deg, rudder {math.degrees(du[1]):+.2f} deg")

    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            "# Generated by tools/lqi_design.py - do not edit by hand.\n"
            f"# Trim: {AIRSPEED} m/s level flight at {ALTITUDE} m (uav-6dof-autopilot model).\n"
            "lqi_controller:\n"
            "  ros__parameters:\n"
            f"    trim_airspeed: {AIRSPEED}\n"
            f"    trim_alpha: {trim.alpha:.8g}\n"
            f"    trim_elevator: {trim.elevator:.8g}\n"
            f"    trim_throttle: {trim.throttle:.8g}\n"
            f"    k_lon: {[float(f'{v:.8g}') for v in K_lon.ravel()]}\n"
            f"    k_lat: {[float(f'{v:.8g}') for v in K_lat.ravel()]}\n"
        )
        print(f"\nWrote {out}")


if __name__ == "__main__":
    main()